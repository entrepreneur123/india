const loaded = { en: EN };
let lang = 'en';

/** Loads a language (lang/<code>.js) once; unknown codes and failed loads fall back to English. */
export async function setLang(code) {
  const meta = LANGS.find((l) => l.code === code);
  if (meta && !loaded[code]) {
    try { loaded[code] = (await import(`./lang/${code}.js`)).default; } catch { /* offline before its first load */ }
  }
  lang = meta && loaded[code] ? code : 'en';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    document.documentElement.dir = LANGS.find((l) => l.code === lang).dir ?? 'ltr';
  }
  return lang;
}
export const getLang = () => lang;
// Digits 0-9 in every language (Marathi, Bengali, Urdu, ... would otherwise get their own digits):
// the same digits as the official notices, roll numbers and fees.
export const locale = () => `${LANGS.find((l) => l.code === lang).locale}-u-nu-latn`;

/** The browser's first language that we have, else English. */
export function guessLang(prefs) {
  for (const p of prefs ?? []) {
    const code = String(p).toLowerCase().split('-')[0];
    if (LANGS.some((l) => l.code === code)) return code;
  }
  return 'en';
}

/** t('updated', {time: '…'}): the string in the current language with {placeholders} filled in. */
export function t(key, vars = {}) {
  const s = loaded[lang]?.[key] ?? EN[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
